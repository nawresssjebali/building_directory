def call_gemini(bio_text: str) -> str:
    prompt = SYSTEM_PROMPT.format(word_cap=BIO_WORD_CAP, bio=bio_text)
    payload = {"contents": [{"parts": [{"text": prompt}]}]}

    for attempt in range(1, MAX_RETRIES + 1):
        resp = requests.post(GEMINI_URL, json=payload, timeout=60)
        if resp.status_code == 200:
            data = resp.json()
            return data["candidates"][0]["content"]["parts"][0]["text"].strip()
        elif resp.status_code == 429:
            wait = REQUEST_DELAY_SECONDS * (2 ** attempt)  # exponential backoff
            print(f"  429 rate-limited, backing off {wait:.1f}s (attempt {attempt}/{MAX_RETRIES})")
            time.sleep(wait)
            continue
        else:
            raise RuntimeError(f"Gemini API error {resp.status_code}: {resp.text[:300]}")
    raise RuntimeError("Exceeded max retries on 429s")


def clean_output(text: str) -> str:
    """Belt-and-suspenders cleanup in case the model ignores instructions."""
    # Strip common leaked preambles
    text = re.sub(r'^(Here\'?s|Here is|Sure[,!]?|Certainly[,!]?)[^\n]*\n+', '', text, flags=re.IGNORECASE)
    # Strip markdown bold/headers
    text = re.sub(r'\*\*(.*?)\*\*', r'\1', text)
    text = re.sub(r'^#+\s*', '', text, flags=re.MULTILINE)
    return text.strip()


def flag_if_suspicious(text: str) -> list[str]:
    """Return a list of issues for a post-run QA pass."""
    issues = []
    if re.match(r'^(Here|Sure|Certainly)', text, flags=re.IGNORECASE):
        issues.append("leaked_preamble")
    if "**" in text or re.search(r'^#+\s', text, flags=re.MULTILINE):
        issues.append("markdown_artifact")
    if len(text.split()) > BIO_WORD_CAP * 1.3:
        issues.append("over_length")
    if text.count('"') >= 2:
        issues.append("possible_verbatim_quote")
    return issues


