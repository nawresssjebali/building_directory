def normalize_batch(raw_numbers):
    """Send one batch of raw phone strings to Gemini and return parsed results."""
    prompt = PROMPT_TEMPLATE.format(batch_json=json.dumps(raw_numbers, ensure_ascii=False))

    response = client.models.generate_content(
        model=MODEL,
        contents=prompt,
        config={
            "response_mime_type": "application/json",
        },
    )

    try:
        results = json.loads(response.text)
    except (json.JSONDecodeError, TypeError) as e:
        raise RuntimeError(f"Failed to parse Gemini response as JSON: {e}\nRaw response: {response.text}")

    if len(results) != len(raw_numbers):
        raise RuntimeError(
            f"Batch size mismatch: sent {len(raw_numbers)}, got {len(results)} back"
        )

    return results


