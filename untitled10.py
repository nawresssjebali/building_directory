def get_initial_state(session):
    r = session.get(FIND_A_DOULA_URL, headers={"user-agent": HEADERS_COMMON["user-agent"]})
    r.raise_for_status()
    html = r.text

    # Try several known patterns for where Laravel/Livewire might expose the CSRF token
    csrf_patterns = [
        r'data-csrf="([^"]+)"',
        r"data-csrf='([^']+)'",
        r'name="csrf-token"\s+content="([^"]+)"',
        r'content="([^"]+)"\s+name="csrf-token"',
        r"name='csrf-token'\s+content='([^']+)'",
        r'<input[^>]*name="_token"[^>]*value="([^"]+)"',
        r'<input[^>]*value="([^"]+)"[^>]*name="_token"',
        r'"csrfToken"\s*:\s*"([^"]+)"',
    ]
    csrf_token = None
    for pat in csrf_patterns:
        m = re.search(pat, html)
        if m:
            csrf_token = m.group(1)
            print(f"Found CSRF token using pattern: {pat}")
            break

    if not csrf_token:
        print("\n=== DIAGNOSTIC: could not find CSRF token with known patterns ===")
        print(f"Page length: {len(html)} chars")
        # Show context around every case-insensitive occurrence of 'csrf' or 'token'
        for keyword in ["csrf", "_token", "csrfToken"]:
            for m in re.finditer(re.escape(keyword), html, re.IGNORECASE):
                start = max(0, m.start() - 80)
                end = min(len(html), m.end() + 80)
                print(f"\n--- match for '{keyword}' at {m.start()} ---")
                print(html[start:end])
        raise RuntimeError(
            "Could not find CSRF token. Copy the DIAGNOSTIC output above and send it back "
            "so the pattern can be fixed."
        )

    # Try to find the Livewire snapshot
    snap_patterns = [
        r'wire:snapshot="({.*?})"',
        r"wire:snapshot='({.*?})'",
        r'wire:initial-data="({.*?})"',
    ]
    snapshot_str = None
    for pat in snap_patterns:
        m = re.search(pat, html, re.DOTALL)
        if m:
            snapshot_str = htmlmod.unescape(m.group(1))
            print(f"Found snapshot using pattern: {pat}")
            break

    if not snapshot_str:
        print("\n=== DIAGNOSTIC: could not find wire:snapshot with known patterns ===")
        for m in re.finditer(r"wire:", html):
            start = max(0, m.start() - 20)
            end = min(len(html), m.end() + 100)
            print(f"\n--- 'wire:' occurrence at {m.start()} ---")
            print(html[start:end])
            break  # just show the first one, there will be many
        raise RuntimeError(
            "Could not find Livewire snapshot. Copy the DIAGNOSTIC output above and send it back."
        )

    return csrf_token, snapshot_str


def livewire_call(session, csrf_token, snapshot_str, method, updates=None):
    payload = {
        "_token": csrf_token,
        "components": [
            {
                "snapshot": snapshot_str,
                "updates": updates or {},
                "calls": [{"path": "", "method": method, "params": []}],
            }
        ],
    }
    r = session.post(LIVEWIRE_URL, headers=HEADERS_COMMON, data=json.dumps(payload))
    r.raise_for_status()
    data = r.json()
    comp = data["components"][0]
    return comp["snapshot"], comp["effects"]["html"]


def parse_doulas(html_fragment):
    soup = BeautifulSoup(html_fragment, "html.parser")
    results = []
    for card in soup.select('div[wire\\:key] a[href^="https://doula.org.uk/doula/"]'):
        href = card.get("href")
        h3 = card.find("h3")
        name = h3.get_text(strip=True) if h3 else None
        title_p = card.select_one("p.text-sm")
        title = title_p.get_text(strip=True) if title_p else None
        dist_span = card.select_one("span.ml-3")
        dist_text = dist_span.get_text(strip=True) if dist_span else ""
        dist_match = re.search(r"([\d.]+)\s*Miles", dist_text)
        distance = float(dist_match.group(1)) if dist_match else None
        slug = href.rstrip("/").split("/")[-1]
        results.append({
            "slug": slug, "name": name, "profile_url": href,
            "title": title, "distance_miles": distance,
        })
    return results


def main():
    session = requests.Session()
    csrf_token, snapshot_str = get_initial_state(session)
    print("Got initial session + snapshot.")

    confirmed = {}  # slug -> record, with matched_district added

    for i, district in enumerate(LONDON_DISTRICTS, 1):
        time.sleep(SLEEP_BETWEEN_CALLS)
        try:
            snapshot_str, html_fragment = livewire_call(
                session, csrf_token, snapshot_str, method="search",
                updates={"postcode": district},
            )
        except Exception as e:
            print(f"[{district}] search failed: {e} — skipping")
            continue

        doulas = parse_doulas(html_fragment)
        zero_dist = [d for d in doulas if d["distance_miles"] == 0.0]

        # Keep loading while the batch is still full of 0-mile results
        # (means there may be more co-located doulas beyond the current amount)
        safety = 0
        while doulas and doulas[-1]["distance_miles"] == 0.0 and safety < 20:
            safety += 1
            time.sleep(SLEEP_BETWEEN_CALLS)
            snapshot_str, html_fragment = livewire_call(
                session, csrf_token, snapshot_str, method="load", updates={},
            )
            doulas = parse_doulas(html_fragment)
            zero_dist = [d for d in doulas if d["distance_miles"] == 0.0]

        for d in zero_dist:
            d["matched_district"] = district
            confirmed[d["slug"]] = d  # dedup by slug; last write wins (fine, same doula)

        print(f"[{i}/{len(LONDON_DISTRICTS)}] {district}: "
              f"{len(zero_dist)} exact matches (total unique so far: {len(confirmed)})")

        # checkpoint every district
        with open(OUT_CSV, "w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(
                f, fieldnames=["slug", "name", "profile_url", "title", "matched_district"]
            )
            writer.writeheader()
            for d in confirmed.values():
                writer.writerow({k: d[k] for k in writer.fieldnames})

    print(f"\nDone. {len(confirmed)} unique confirmed Doula UK members saved to {OUT_CSV}")


if __name__ == "__main__":
    main()

