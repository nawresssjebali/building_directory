def load_checkpoint(path: str) -> dict:
    if os.path.exists(path):
        with open(path) as f:
            return json.load(f)
    return {}


def save_checkpoint(path: str, checkpoint: dict) -> None:
    with open(path, "w") as f:
        json.dump(checkpoint, f, ensure_ascii=False, indent=2)


def rewrite_bios(df: pd.DataFrame, checkpoint_path: str) -> pd.DataFrame:
    checkpoint = load_checkpoint(checkpoint_path)
    qa_flags = {}

    for i, row in df.iterrows():
        slug = row["slug"]
        if slug in checkpoint:
            continue  # already done — resumable
        if pd.isna(row.get("bio")):
            continue  # nothing to rewrite

        print(f"[{i+1}/{len(df)}] Rewriting bio for {row['name']} ({slug})")
        try:
            raw = call_gemini(row["bio"])
        except RuntimeError as e:
            print(f"  FAILED: {e}")
            continue

        cleaned = clean_output(raw)
        issues = flag_if_suspicious(cleaned)
        if issues:
            qa_flags[slug] = issues
            print(f"  QA flags: {issues}")

        checkpoint[slug] = cleaned
        save_checkpoint(checkpoint_path, checkpoint)  # save after EVERY row
        time.sleep(REQUEST_DELAY_SECONDS)

    df["bio_rewritten"] = df["slug"].map(checkpoint).combine_first(df.get("bio_rewritten"))

    if qa_flags:
        qa_path = "bio_rewrite_qa_flags.json"
        with open(qa_path, "w") as f:
            json.dump(qa_flags, f, indent=2)
        print(f"\n{len(qa_flags)} bios flagged for manual QA — see {qa_path}")

    return df


