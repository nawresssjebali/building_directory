"""
Build an authoritative list of Greater London outward postcodes (outcodes)
using postcodes.io's /outcodes reverse-geocode endpoint, instead of a
hand-typed list.

Strategy: postcodes.io caps radius at 25,000m and limit at 100 per call, and
Greater London spans roughly 50km across -- so one call from the centre
isn't enough. We query from several spread-out points across Greater London
(with generous overlap) and take the union, then filter to only outcodes
whose admin_district is an actual London borough (or the City of London) --
this protects against e.g. KT/DA/BR/TW postcodes that dip into Kent/Surrey
just outside Greater London.

Run in Colab: no extra installs needed beyond `requests` (already in Colab).
"""

import requests
import time
import json

OUTCODES_URL = "https://api.postcodes.io/outcodes"

# Spread-out query centres across Greater London, chosen so 25km-radius
# circles from each overlap and jointly cover the whole of Greater London.
QUERY_CENTRES = [
    ("Central",   -0.1275, 51.5136),   # Covent Garden / WC2
    ("North",     -0.0900, 51.5880),   # Haringey / Enfield border
    ("South",     -0.0982, 51.3762),   # Croydon
    ("East",       0.1834, 51.5764),   # Romford
    ("West",      -0.4790, 51.5464),   # Uxbridge
    ("Southeast",  0.0198, 51.4039),   # Bromley
    ("Southwest", -0.3064, 51.4085),   # Kingston upon Thames
    ("Northwest", -0.3360, 51.5809),   # Harrow
]

# Greater London's 32 boroughs + City of London (normalised, lowercase,
# substring-matched against admin_district values returned by the API).
LONDON_BOROUGHS = {
    "barking and dagenham", "barnet", "bexley", "brent", "bromley", "camden",
    "croydon", "ealing", "enfield", "greenwich", "hackney",
    "hammersmith and fulham", "haringey", "harrow", "havering", "hillingdon",
    "hounslow", "islington", "kensington and chelsea", "kingston upon thames",
    "lambeth", "lewisham", "merton", "newham", "redbridge",
    "richmond upon thames", "southwark", "sutton", "tower hamlets",
    "waltham forest", "wandsworth", "westminster", "city of london",
}


def is_london_borough(admin_district_list):
    if not admin_district_list:
        return False
    return any(d.strip().lower() in LONDON_BOROUGHS for d in admin_district_list)


def fetch_outcodes_near(lon, lat, radius=25000, limit=100):
    r = requests.get(OUTCODES_URL, params={
        "lon": lon, "lat": lat, "radius": radius, "limit": limit,
    })
    r.raise_for_status()
    data = r.json()
    return data.get("result", []) or []


def main():
    all_outcodes = {}  # outcode -> record

    for name, lon, lat in QUERY_CENTRES:
        print(f"Querying near {name} ({lat}, {lon})...")
        results = fetch_outcodes_near(lon, lat)
        print(f"  -> {len(results)} outcodes returned")
        for rec in results:
            all_outcodes[rec["outcode"]] = rec
        time.sleep(0.5)

    print(f"\nTotal unique outcodes across all query points: {len(all_outcodes)}")

    # Filter to genuine Greater London boroughs
    london_only = {
        code: rec for code, rec in all_outcodes.items()
        if is_london_borough(rec.get("admin_district"))
    }
    print(f"After filtering to Greater London boroughs: {len(london_only)}")

    excluded = sorted(set(all_outcodes) - set(london_only))
    if excluded:
        print(f"\nExcluded (outside Greater London boroughs), for sanity-checking: {excluded}")

    final_list = sorted(london_only.keys())
    print(f"\nFinal London outcode count: {len(final_list)}")

    with open("/content/london_outcodes.json", "w") as f:
        json.dump(final_list, f, indent=2)
    print("Saved to /content/london_outcodes.json")

    # Also print as a Python list literal, ready to paste into the scraper script
    print("\nPython list literal:\n")
    print(final_list)


if __name__ == "__main__":
    main()

