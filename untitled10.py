class ProxyUnavailableError(Exception):
    """Raised if a localhost proxy timeout still occurs even after
    bypassing the SDK. If you see this, the interception is happening
    at a network layer below `requests` (e.g. DNS or OS routing), not
    inside the Google SDK's auth session."""


def _is_proxy_timeout(exc: Exception) -> bool:
    msg = str(exc)
    return "localhost:40443" in msg or ("Read timed out" in msg and "localhost" in msg)


def rewrite_bio(bio_text: str) -> str:
    if not isinstance(bio_text, str) or not bio_text.strip():
        return bio_text
    prompt = PROMPT_TEMPLATE.format(bio=bio_text)

    payload = {
        "contents": [{"parts": [{"text": prompt}]}]
    }
    headers = {"Content-Type": "application/json"}
    params = {"key": API_KEY}

    max_retries = 3
    for attempt in range(max_retries):
        try:
            resp = session.post(
                API_URL,
                params=params,
                headers=headers,
                json=payload,
                timeout=30.0,
            )
            resp.raise_for_status()
            data = resp.json()

            candidates = data.get("candidates", [])
            if not candidates:
                # Usually means it was blocked by safety filters
                reason = data.get("promptFeedback", {}).get("blockReason", "unknown")
                print(f"  -> No candidates returned (blockReason={reason})")
                return None

            parts = candidates[0].get("content", {}).get("parts", [])
            text = "".join(p.get("text", "") for p in parts).strip()
            return text if text else None

        except requests.exceptions.RequestException as e:
            if _is_proxy_timeout(e):
                print(f"  -> Proxy still intercepting even with direct requests call: {e}")
                raise ProxyUnavailableError(str(e)) from e
            if attempt < max_retries - 1:
                print(
                    f"  -> Attempt {attempt + 1} failed. Retrying in 3 seconds... ({e})"
                )
                time.sleep(3)
            else:
                print(f"  -> Failed after {max_retries} attempts: {e}")
                return None
    return None


