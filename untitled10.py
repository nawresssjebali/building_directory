import pandas as pd

df = pd.read_csv('doula_uk_cleaned_v17.csv')  # or v16, whichever you're on

def classify(cat):
    if pd.isna(cat):
        return 'none'
    if cat == 'website':
        return 'website'
    if cat in ['instagram', 'facebook', 'linktree_or_biolink', 'google_sites', 'social_handle_ambiguous', 'directory_listing']:
        return 'social'
    return 'other'

df['website_type'] = df['website_category'].apply(classify)

df.to_csv('doula_uk_cleaned_v18.csv', index=False)