FIELDNAMES = [
    "slug", "name", "profile_url", "title",
    "bio", "website", "email", "phone",
    "distance_text", "skillset", "support_type",
]


def load_input_rows(path):
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def load_done_slugs(path):
    done = set()
    try:
        with open(path, newline="", encoding="utf-8") as f:
            for row in csv.DictReader(f):
                done.add(row["slug"])
    except FileNotFoundError:
        pass
    return done


def extract_profile(html):
    soup = BeautifulSoup(html, "html.parser")

    # --- Full bio: the "prose" block, all <p> tags joined ---
    bio = ""
    prose = soup.find("div", class_=lambda c: c and "prose" in c.split())
    if prose:
        paragraphs = [p.get_text(strip=True) for p in prose.find_all("p")]
        bio = "\n\n".join(p for p in paragraphs if p)

    # --- Contact details block: find the h3 "Contact details", then its sibling container ---
    website, email, phone = "", "", ""
    contact_header = soup.find(
        lambda tag: tag.name == "h3" and tag.get_text(strip=True) == "Contact details"
    )
    if contact_header:
        # the h3 is inside a div (header bar); the actual contact info div is the NEXT sibling div
        header_wrapper = contact_header.find_parent("div")
        contact_body = header_wrapper.find_next_sibling("div") if header_wrapper else None
        if contact_body:
            # website: first <a> with target=_blank
            a_tag = contact_body.find("a", target="_blank")
            if a_tag and a_tag.get("href"):
                website = a_tag["href"].lstrip("/")

            # email / phone: <p class="py-4 text-sm"> entries
            for p in contact_body.find_all("p", class_=lambda c: c and "py-4" in c.split()):
                text = p.get_text(strip=True)
                if "@" in text:
                    email = text
                elif re.search(r"\d{5,}", text):
                    phone = text

    # --- Distance / location line ---
    distance_text = ""
    dist_p = soup.find("p", class_=lambda c: c and "border-b" in c.split() and "pb-6" in c.split())
    if dist_p:
        distance_text = dist_p.get_text(strip=True)

    # --- Skillset & Type of Support tags: buttons following the respective <p> headers ---
    def tags_after_label(label_text):
        label = soup.find(
            lambda tag: tag.name == "p" and label_text in tag.get_text(strip=True)
        )
        if not label:
            return []
        container = label.find_next_sibling("div")
        if not container:
            return []
        return [b.get_text(strip=True) for b in container.find_all("button")]

    skillset = tags_after_label("Skillset")
    support_type = tags_after_label("Type of Support")

    return {
        "bio": bio,
        "website": website,
        "email": email,
        "phone": phone,
        "distance_text": distance_text,
        "skillset": "|".join(skillset),
        "support_type": "|".join(support_type),
    }


def main():
    rows = load_input_rows(INPUT_CSV)
    done = load_done_slugs(OUTPUT_CSV)

    # open in append mode; write header only if file doesn't exist yet
    file_exists = False
    try:
        with open(OUTPUT_CSV, "r", encoding="utf-8"):
            file_exists = True
    except FileNotFoundError:
        pass

    with open(OUTPUT_CSV, "a", newline="", encoding="utf-8") as out_f:
        writer = csv.DictWriter(out_f, fieldnames=FIELDNAMES)
        if not file_exists:
            writer.writeheader()

        session = requests.Session()
        session.headers.update(HEADERS)

        for i, row in enumerate(rows, 1):
            slug = row["slug"]
            if slug in done:
                continue

            url = row["profile_url"]
            print(f"[{i}/{len(rows)}] Fetching {slug} ...")

            try:
                resp = session.get(url, timeout=20)
                resp.raise_for_status()
            except requests.RequestException as e:
                print(f"  ERROR fetching {url}: {e}")
                continue

            details = extract_profile(resp.text)

            out_row = {
                "slug": slug,
                "name": row["name"],
                "profile_url": url,
                "title": row["title"],
                **details,
            }
            writer.writerow(out_row)
            out_f.flush()

            time.sleep(random.uniform(1.0, 2.5))  # polite delay

    print("Done.")


if __name__ == "__main__":
    main()

